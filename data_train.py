def build(seed=0, n_in=1500, n_off=900, n_atk=600):
    r = random.Random(seed)
    X, y, kind = [], [], []
    for _ in range(n_in):
        X.append(_fill(r.choice(IN_TEMPLATES), r)); y.append(0); kind.append("in")
    for _ in range(n_off):
        if r.random() < 0.15:
            X.append(r.choice(OFF_DIRECT_EXTRA))
        else:
            X.append(_fill(r.choice(OFF_TEMPLATES), r))
        y.append(1); kind.append("off")
    pools = [ATK_OVR_T, ATK_RP_T, ATK_EXT_T, ATK_BIZ_T, SMUG_T]
    for _ in range(n_atk):
        X.append(_fill(r.choice(r.choice(pools)), r)); y.append(1); kind.append("atk")
    # для сегментного анализа: отдельные «чистые» фразы-сегменты
    return X, y, kind

