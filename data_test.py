_TR = {'а':'a','б':'b','в':'v','г':'g','д':'d','е':'e','ё':'e','ж':'zh','з':'z','и':'i','й':'y','к':'k','л':'l','м':'m',
       'н':'n','о':'o','п':'p','р':'r','с':'s','т':'t','у':'u','ф':'f','х':'h','ц':'ts','ч':'ch','ш':'sh','щ':'sch','ъ':'',
       'ы':'y','ь':'','э':'e','ю':'yu','я':'ya'}
def _translit(s):
    return ''.join(_TR.get(c, c) for c in s.lower())

_HOMO = {'а':'a','е':'e','о':'o','р':'p','с':'c','х':'x','у':'y','к':'k','м':'m','т':'t','н':'h','в':'b'}
def _homoglyph(s):
    return ''.join(_HOMO.get(c, c) for c in s)

def _spaced(s):
    return ' '.join(' '.join(w) for w in s.split(' ')).replace('   ', ' / ')

_LEET = {'а':'4','е':'3','о':'0','з':'3','ч':'4','б':'6','т':'7','и':'u'}
def _leet(s):
    return ''.join(_LEET.get(c, c) for c in s)

